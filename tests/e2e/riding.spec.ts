import { test, expect } from '@playwright/test';
test('M1: renders bike, keyboard riding, steering, boost, recharge, pause and reset', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('requestfailed', request => errors.push(request.url()));
  await page.goto('/');
  await expect(page.locator('#error')).toBeHidden();
  await expect(page.locator('#speed')).toHaveText('000');
  await expect(page.locator('#overlay')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('01-start.png') });
  await page.locator('#ride').click();
  await expect(page.locator('#overlay')).toBeHidden();
  await page.keyboard.press('F3');
  await page.keyboard.down('KeyW');
  await expect.poll(async () => Number(await page.locator('#speed').textContent())).toBeGreaterThan(70);
  const xBefore = Number((await page.locator('#debug').textContent())?.match(/x ([\d.-]+)/)?.[1]);
  await page.keyboard.down('KeyD'); await page.waitForTimeout(400); await page.keyboard.up('KeyD');
  await page.waitForTimeout(200);
  const xAfter = Number((await page.locator('#debug').textContent())?.match(/x ([\d.-]+)/)?.[1]);
  expect(xAfter).toBeGreaterThan(xBefore + 0.1);
  await page.screenshot({ path: testInfo.outputPath('02-riding.png') });
  await page.keyboard.up('KeyW'); await page.keyboard.down('KeyS');
  await expect.poll(async () => Number(await page.locator('#speed').textContent())).toBe(0); await page.keyboard.up('KeyS');
  await page.keyboard.press('KeyR'); await expect(page.locator('#distance')).toHaveText('0008');
  // Arrow mapping, simultaneous controls, and functional boost above normal cap.
  await page.keyboard.down('ArrowUp');
  await expect.poll(async () => Number(await page.locator('#speed').textContent()), { timeout: 8000 }).toBeGreaterThan(155);
  await page.keyboard.down('ShiftLeft');
  await expect.poll(async () => Number(await page.locator('#speed').textContent())).toBeGreaterThan(165);
  await expect.poll(async () => Number(await page.locator('#nitro-value').textContent())).toBeLessThan(70);
  await page.screenshot({ path: testInfo.outputPath('03-nitro.png') });
  await testInfo.attach('renderer-telemetry', { body: (await page.locator('#debug').textContent()) || '', contentType: 'text/plain' });
  await page.keyboard.up('ShiftLeft');
  const reserve = Number(await page.locator('#nitro-value').textContent());
  await page.waitForTimeout(1300);
  expect(Number(await page.locator('#nitro-value').textContent())).toBeLessThanOrEqual(reserve);
  await expect.poll(async () => Number(await page.locator('#nitro-value').textContent()), { timeout: 4000 }).toBeGreaterThan(reserve + 5);
  expect(Number(await page.locator('#speed').textContent())).toBeLessThanOrEqual(160);
  await page.keyboard.press('Escape'); await page.keyboard.up('ArrowUp');
  await expect(page.locator('#overlay')).toBeVisible();
  const pausedDistance = await page.locator('#distance').textContent(); await page.waitForTimeout(600);
  await expect(page.locator('#distance')).toHaveText(pausedDistance || '');
  await page.locator('#ride').click();
  await page.keyboard.press('KeyR');
  await expect(page.locator('#speed')).toHaveText('000'); await expect(page.locator('#nitro-value')).toHaveText('100');
  // Right/left arrow controls and input clearing after focus loss.
  await page.keyboard.down('ArrowUp'); await page.keyboard.down('ArrowLeft'); await page.waitForTimeout(700);
  await page.keyboard.up('ArrowLeft'); await page.keyboard.down('ArrowRight'); await page.waitForTimeout(300);
  await page.keyboard.up('ArrowRight');
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await page.keyboard.up('ArrowUp'); await expect(page.locator('#overlay')).toBeVisible();
  await page.locator('#ride').click(); await page.keyboard.press('KeyR');
  await page.setViewportSize({ width: 1024, height: 768 });
  await expect(page.locator('#game')).toHaveJSProperty('width', 1024);
  await expect(page.locator('#error')).toBeHidden();
  expect(errors).toEqual([]);
});

